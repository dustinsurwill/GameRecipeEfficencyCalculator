"""
Factorio importer — reads recipes, machines and resources straight from an installed game.

Factorio ships its data as plain Lua (`<game>/data/<mod>/prototypes/...`). `factorio_data.lua` runs those
files in a sandbox (needs the `lua` binary, e.g. `lua5.4`) and prints recipes, crafting machines, mining
drills, resources and fluid tiles as JSON; everything after that is plain Python.

    uv run python -m app.importer.factorio [--factorio-dir ~/.local/share/Steam/steamapps/common/Factorio]

Two packs are (re)created for the installed version:
  * Vanilla   — the base game
  * Space Age — base + Space Age + Quality + Elevated Rails, with Space Age's changes to base recipes
                applied (new crafting categories, changed ingredients), so the base mod has its own
                mod version in that pack ("2.1.24 (Space Age)").

Ids are namespaced by the mod that defines the thing (`base:iron-plate`, `space-age:holmium-plate`),
fluids get the usual `fluid:` prefix. Mining drills, pumpjacks and offshore pumps are recipes with no
inputs (or only the fluid a resource needs), so every raw material has a producer in the route graph.
A recipe that several machines can craft (circuits: assembling machine or electromagnetic plant) is
stored once per machine. Crafting time is kept in `time_ticks` and machine speeds in
`MachineIdentity.speed_tiers_json`, which is what the throughput calculation uses.

Re-running replaces everything this importer wrote (import keys starting `factorio/`); recipes
contributed by hand are untouched.

Known gaps: boilers/burning/spoilage, recycling recipes (generated by the game at load time), fluid
temperatures, planet restrictions (`surface_conditions`) and resource yield %.
"""
