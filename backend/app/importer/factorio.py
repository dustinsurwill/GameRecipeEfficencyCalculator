def machine_for_category(category: str) -> str:
    if category.startswith("mining-"):
        return RESOURCE_MACHINES.get(category.removeprefix("mining-"), "Mining Drill")
    if category == PUMP_CATEGORY:
        return PUMP_MACHINE
    return CATEGORY_MACHINES.get(category, category.replace("-", " ").title())


# ── Reading the game ──────────────────────────────────────────────────────────

def _find_lua() -> str:
    for name in ("lua5.4", "lua", "luajit", "lua5.3"):
        if shutil.which(name):
            return name
    raise SystemExit("A Lua interpreter is required (install lua5.4) to read Factorio's data files.")


def load_pack_data(data_dir: Path, pack: PackDef) -> dict[str, list[dict[str, Any]]]:
    args = [f"load:{mod}:{rel}" for mod in pack.mods for rel in MOD_FILES[mod]]
    args += [f"update:{mod}:{rel}" for mod in pack.mods for rel in MOD_UPDATES.get(mod, [])]
    proc = subprocess.run(
        [_find_lua(), str(LUA_DRIVER), str(data_dir), *args],
        capture_output=True, text=True, check=False, timeout=300,
    )
    if proc.returncode != 0:
        raise SystemExit(f"Lua failed reading {data_dir}:\n{proc.stderr[-2000:]}")
    return json.loads(proc.stdout)


def mod_version(data_dir: Path, mod: str) -> str:
    return json.loads((data_dir / mod / "info.json").read_text())["version"]


def load_names(data_dir: Path, mods: list[str]) -> dict[str, str]:
    """Display names from the English locale: 'iron-plate' -> 'Iron plate'. Item names win over fluid
    names over entity names (an item is usually the placeable entity's item)."""
    names: dict[str, dict[str, str]] = {"entity-name": {}, "fluid-name": {}, "item-name": {}}
    for mod in mods:
        for cfg in (data_dir / mod / "locale" / "en").glob("*.cfg"):
            section = None
            for line in cfg.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line.startswith("[") and line.endswith("]"):
                    section = line[1:-1]
                elif section in names and "=" in line and not line.startswith(("#", ";")):
                    key, _, value = line.partition("=")
                    names[section].setdefault(key.strip(), value.strip())
    return {**names["entity-name"], **names["fluid-name"], **names["item-name"]}


class Owners:
    """Which mod defines an item/fluid name: the first mod (in load order) whose prototype files mention
    `name = "<name>"`. Recipes and technologies are excluded because they only *reference* things."""

    def __init__(self, data_dir: Path, mods: list[str]) -> None:
        self.mods = mods
        self.texts: dict[str, str] = {}
        for mod in mods:
            chunks = []
            for f in (data_dir / mod / "prototypes").rglob("*.lua"):
                if f.parent.name == "recipe" or f.name.startswith(("recipe", "technology", "tips")):
                    continue
                chunks.append(f.read_text(encoding="utf-8", errors="replace"))
            self.texts[mod] = "\n".join(chunks)
        self.cache: dict[str, str] = {}

    def __call__(self, name: str) -> str:
        if name not in self.cache:
            pattern = re.compile(r'\bname\s*=\s*"' + re.escape(name) + '"')
            self.cache[name] = next((m for m in self.mods if pattern.search(self.texts[m])), self.mods[0])
        return self.cache[name]


# ── Recipe entries -> pipeline Recipes ────────────────────────────────────────

def _amount(entry: dict[str, Any]) -> float:
    """Expected amount of one ingredient/product entry (chances and ranges folded in)."""
    if "amount" in entry:
        qty = float(entry["amount"])
    else:
        qty = (float(entry.get("amount_min", 0)) + float(entry.get("amount_max", 0))) / 2
    prob = float(entry.get("probability", 1))
    prob *= float(entry.get("independent_probability", 1))
    shared = entry.get("shared_probability")
    if isinstance(shared, dict):
        prob *= float(shared.get("max", 1)) - float(shared.get("min", 0))
    return qty * prob


def _is_certain(entry: dict[str, Any]) -> bool:
    return (entry.get("probability", 1) == 1 and entry.get("independent_probability", 1) == 1
            and "shared_probability" not in entry)


def _entries(raw: Any) -> list[dict[str, Any]]:
    """Normalise a recipe's ingredients/results list (also accepts the old `{"iron-plate", 2}` form)."""
    out = []
    for e in raw or []:
        if isinstance(e, list):
            e = {"type": "item", "name": e[0], "amount": e[1]}
        out.append(e)
    return out


def _net(ingredients: list[dict], results: list[dict]) -> tuple[dict, dict]:
    """Per (type, name) totals, with catalysts (amounts returned unchanged, e.g. Kovarex's U-235)
    cancelled out. A catalyst is only cancelled when the product side is certain (no chance)."""
    ins: dict[tuple[str, str], float] = {}
    outs: dict[tuple[str, str], float] = {}
    cat_in: dict[tuple[str, str], float] = {}
    cat_out: dict[tuple[str, str], float] = {}
    for e in ingredients:
        k = (e.get("type", "item"), e["name"])
        ins[k] = ins.get(k, 0) + _amount(e)
        cat_in[k] = cat_in.get(k, 0) + float(e.get("ignored_by_stats", 0))
    for e in results:
        k = (e.get("type", "item"), e["name"])
        outs[k] = outs.get(k, 0) + _amount(e)
        if _is_certain(e):
            cat_out[k] = cat_out.get(k, 0) + float(e.get("ignored_by_stats", 0))
    for k in set(cat_in) & set(cat_out):
        cancel = min(cat_in[k], cat_out[k], ins.get(k, 0), outs.get(k, 0))
        ins[k] = ins.get(k, 0) - cancel
        outs[k] = outs.get(k, 0) - cancel
    return ({k: v for k, v in ins.items() if v > 1e-9}, {k: v for k, v in outs.items() if v > 1e-9})


def _slots(flows: dict, owner: Callable[[str], str]) -> tuple[list[Slot], list[Slot]]:
    """(item slots, fluid slots) for one side of a recipe."""
    items, fluids = [], []
    for (kind, name), qty in flows.items():
        slot = Slot(tag=None, item=f"{owner(name)}:{name}", count=round(qty, 6), fluid=(kind == "fluid"))
        (fluids if kind == "fluid" else items).append(slot)
    return items, fluids


def _make(pack: str, mod: str, key: str, category_ns: str, category: str, ticks: int,
          ins: dict, outs: dict, owner: Callable[[str], str], productivity: bool = False) -> CliRecipe:
    in_items, in_fluids = _slots(ins, owner)
    out_items, out_fluids = _slots(outs, owner)
    return CliRecipe(
        id=f"factorio/{pack}/{mod}/{key}",
        type=f"{category_ns}:{category}",
        machine=machine_for_category(category),
        namespace=mod,
        inputs=in_items,
        outputs=out_items + out_fluids,     # fluid outputs are ordinary output slots flagged as fluid
        aux_inputs=in_fluids,
        time_ticks=ticks,
        allow_productivity=productivity,
    )


def convert_recipes(
    raw: list[dict[str, Any]], owner: Callable[[str], str], pack: str = "pack",
    category_mod: Callable[[str, str], str] = lambda category, fallback: fallback,
) -> list[CliRecipe]:
    """Raw Lua recipe tables -> pipeline Recipes. `owner(name)` returns the mod that defines a name;
    `category_mod(category, fallback)` the mod that defines a crafting category."""
    recipes: list[CliRecipe] = []
    for r in raw:
        if r.get("parameter") or r.get("hidden"):
            continue
        ins, outs = _net(_entries(r.get("ingredients")), _entries(r.get("results")))
        if not ins or not outs:
            continue            # nothing to chain through (spawner eggs etc.)
        categories = r.get("categories") or ([r["category"]] if r.get("category") else ["crafting"])
        ticks = round(float(r.get("energy_required", 0.5)) * 60)
        seen: set[str] = set()
        for category in categories:
            if category in HAND_ONLY and len(categories) > 1:
                continue            # players can hand-craft it; the machines are what we model
            machine = machine_for_category(category)
            if machine in seen:
                continue
            seen.add(machine)
            key = f"recipe/{r['name']}" + (f"@{category}" if len(seen) > 1 else "")
            recipes.append(_make(pack, r["__mod"], key, category_mod(category, r["__mod"]), category,
                                 ticks, ins, outs, owner, bool(r.get("allow_productivity"))))
    return recipes


def mining_recipes(
    resources: list[dict[str, Any]], tiles: list[dict[str, Any]], pump_mod: str, owner: Callable[[str], str],
    pack: str = "pack",
) -> list[CliRecipe]:
    """Mining drill / pumpjack recipes from resource prototypes, offshore pump recipes from fluid tiles."""
    out: list[CliRecipe] = []
    for res in resources:
        minable = res.get("minable") or {}
        if "results" in minable:
            results = _entries(minable["results"])
        elif minable.get("result"):
            results = [{"type": "item", "name": minable["result"], "amount": minable.get("count", 1)}]
        else:
            continue
        ins: dict = {}
        if minable.get("required_fluid"):
            ins[("fluid", minable["required_fluid"])] = float(minable.get("fluid_amount", 1))
        _, outs = _net([], results)
        if not outs:
            continue
        category = "mining-" + res.get("category", "basic-solid")
        ticks = round(float(minable.get("mining_time", 1)) * 60)
        out.append(_make(pack, res["__mod"], f"mining/{res['name']}", res["__mod"], category, ticks,
                         ins, outs, owner))
    seen: set[str] = set()
    for tile in sorted(tiles, key=lambda t: (t.get("__mod", pump_mod) != pump_mod, t["name"])):
        fluid = tile.get("fluid")
        if not fluid or fluid in seen:
            continue
        seen.add(fluid)
        # one offshore pump moves 20 units/tick = 1200/s; the recipe is one second of pumping
        # the pump recipe belongs to the mod that defines the tile (Fulgora's oil ocean is Space Age's)
        out.append(_make(pack, tile.get("__mod", pump_mod), f"pumping/{fluid}", pump_mod, PUMP_CATEGORY, 60,
                         {}, {("fluid", fluid): 1200.0}, owner))
    return out


def _kw(text: Any) -> float:
    """'150kW' -> 150, '2MW' -> 2000, '500W' -> 0.5 (kilowatts)."""
    m = re.match(r"^\s*([\d.]+)\s*([kKMG]?)W", str(text or ""))
    if not m:
        return 0.0
    return float(m.group(1)) * {"": 0.001, "k": 1, "K": 1, "M": 1000, "G": 1e6}[m.group(2)]


def _effects(value: Any) -> list[str]:
    return [value] if isinstance(value, str) else list(value or [])


def speed_tiers(pack_data: dict[str, list[dict]], names: dict[str, str]) -> dict[str, list[dict]]:
    """Machine identity name -> tiers, one per machine that can run its recipes:
    {name, speed, categories, mod, power_kw, fuel (burner machines: power_kw is fuel power), module_slots,
     allowed_effects}."""
    tiers: dict[str, list[dict]] = {}

    def add(machine: str, entity: dict, speed: float, categories: list[str]) -> None:
        source = (entity.get("energy_source") or {}).get("type")
        tiers.setdefault(machine, []).append({
            "name": names.get(entity["name"], entity["name"].replace("-", " ").capitalize()),
            "speed": speed, "categories": categories, "mod": entity["__mod"],
            "power_kw": _kw(entity.get("energy_usage")), "fuel": source == "burner",
            "module_slots": int(entity.get("module_slots") or 0),
            "allowed_effects": _effects(entity.get("allowed_effects")),
        })

    for kind in ("assembling-machine", "furnace", "rocket-silo"):
        for e in pack_data.get(kind, []):
            cats = e.get("crafting_categories") or []
            for machine in dict.fromkeys(machine_for_category(c) for c in cats):
                add(machine, e, float(e.get("crafting_speed", 1)), cats)
    for e in pack_data.get("mining-drill", []):
        cats = ["mining-" + c for c in (e.get("resource_categories") or [])]
        for machine in dict.fromkeys(machine_for_category(c) for c in cats):
            add(machine, e, float(e.get("mining_speed", 1)), cats)
    for e in pack_data.get("offshore-pump", []):
        add(PUMP_MACHINE, e, 1.0, [PUMP_CATEGORY])
    for lst in tiers.values():
        lst.sort(key=lambda t: (t["speed"], t["name"]))
    return tiers


# Module effects the calculator uses -> MachineUpgradeModifier.modifier_type. Values are additive
# fractions (speed 0.2 = +20%), so `stacks_additively` is True; consumption is negative for efficiency.
MODULE_MODIFIERS = {"speed": "SPEED", "productivity": "YIELD_BONUS", "consumption": "ENERGY_USE"}


def module_catalog(pack_data: dict[str, list[dict]], names: dict[str, str], owner: Callable[[str], str]) -> list[dict]:
    out = []
    for m in pack_data.get("module", []):
        effects = {k: float(v) for k, v in (m.get("effect") or {}).items() if k in MODULE_MODIFIERS and v}
        if effects and m.get("category") != "quality":     # quality is not modelled, so its modules are skipped
            out.append({"item_id": f"{owner(m['name'])}:{m['name']}", "name": names.get(m["name"], m["name"]), "effects": effects})
    return out


# ── Database ──────────────────────────────────────────────────────────────────

async def _purge() -> None:
    """Remove everything an earlier run wrote so a re-import reflects the current game files."""
    async with async_session_factory() as session:
        async with session.begin():
            keyed = select(Recipe.id).where(Recipe.import_key.like("factorio/%"))
            await session.exec(delete(RecipeSlot).where(RecipeSlot.recipe_id.in_(keyed)))
            await session.exec(delete(RecipeModVersionLink).where(RecipeModVersionLink.recipe_id.in_(keyed)))
            await session.exec(delete(Recipe).where(Recipe.import_key.like("factorio/%")))
            game = (await session.exec(select(Game).where(Game.slug == "factorio"))).scalars().one_or_none()
            if game is None:
                return
            # a pack's mod versions are re-linked on import (the Space Age pack gets its own base version)
            pack_versions = select(ModPackVersion.id).join(
                ModPackIdentity, ModPackIdentity.id == ModPackVersion.identity_id
            ).where(ModPackIdentity.game_id == game.id)
            await session.exec(delete(ModPackModVersion).where(ModPackModVersion.modpack_id.in_(pack_versions)))
            machines = select(MachineIdentity.id).where(MachineIdentity.game_id == game.id)
            upgrades = select(MachineUpgradeItem.id).where(MachineUpgradeItem.machine_id.in_(machines))
            await session.exec(delete(MachineUpgradeModifier).where(MachineUpgradeModifier.upgrade_item_id.in_(upgrades)))
            await session.exec(delete(MachineUpgradeItem).where(MachineUpgradeItem.machine_id.in_(machines)))
            mod_versions = select(ModVersion.id).join(Mod, Mod.id == ModVersion.mod_id).where(Mod.game_id == game.id)
            used = select(RecipeSlot.item_appearance_id).where(RecipeSlot.item_appearance_id.is_not(None))
            await session.exec(
                delete(ItemAppearance).where(ItemAppearance.mod_version_id.in_(mod_versions),
                                             ItemAppearance.id.not_in(used))
            )
            has_recipes = exists().where(Recipe.machine_identity_id == MachineIdentity.id)
            await session.exec(
                delete(MachineIdentity).where(MachineIdentity.game_id == game.id, ~has_recipes)
            )


async def _apply_display_names(names: dict[str, str]) -> int:
    """Replace the derived canonical names with Factorio's own ('Uranium-235'). Item identities store
    their id in `notes` as 'item_id:<id>'."""
    changed = 0
    async with async_session_factory() as session:
        async with session.begin():
            game = (await session.exec(select(Game).where(Game.slug == "factorio"))).scalars().one()
            rows = (await session.exec(select(ItemIdentity).where(ItemIdentity.game_id == game.id))).scalars().all()
            for ident in rows:
                item_id = (ident.notes or "").removeprefix("item_id:").removeprefix("fluid:")
                name = names.get(item_id.partition(":")[2])
                if name:
                    pretty = name[:1].upper() + name[1:]
                    if pretty != ident.canonical_name:
                        ident.canonical_name = pretty
                        session.add(ident)
                        changed += 1
    return changed


async def _apply_machine_data(tiers: dict[str, list[dict]]) -> None:
    async with async_session_factory() as session:
        async with session.begin():
            game = (await session.exec(select(Game).where(Game.slug == "factorio"))).scalars().one()
            await session.exec(
                update(MachineIdentity).where(MachineIdentity.game_id == game.id).values(is_time_based=True)
            )
            for name, lst in tiers.items():
                await session.exec(
                    update(MachineIdentity)
                    .where(MachineIdentity.game_id == game.id, MachineIdentity.name == name)
                    .values(speed_tiers_json=json.dumps(lst))
                )


async def _apply_modules(modules: list[dict], tiers: dict[str, list[dict]]) -> int:
    """Every machine with module slots gets the game's modules as upgrade items (max_slots = its biggest tier).
    Which effects a tier accepts is in the tier data (`allowed_effects`)."""
    made = 0
    async with async_session_factory() as session:
        async with session.begin():
            game = (await session.exec(select(Game).where(Game.slug == "factorio"))).scalars().one()
            machines = {m.name: m for m in (await session.exec(
                select(MachineIdentity).where(MachineIdentity.game_id == game.id))).scalars().all()}
            for machine_name, lst in tiers.items():
                slots = max((t["module_slots"] for t in lst), default=0)
                if not slots or machine_name not in machines:
                    continue
                for mod in modules:
                    appearance = (await session.exec(
                        select(ItemAppearance).where(ItemAppearance.item_id == mod["item_id"]).limit(1)
                    )).scalars().first()
                    item = MachineUpgradeItem(
                        machine_id=machines[machine_name].id, item_appearance_id=appearance.id if appearance else None,
                        display_name=mod["name"], max_slots=slots, data_source="game files",
                    )
                    session.add(item)
                    await session.flush()
                    for effect, value in mod["effects"].items():
                        session.add(MachineUpgradeModifier(
                            upgrade_item_id=item.id, modifier_type=MODULE_MODIFIERS[effect], multiplier=value,
                            stacks_additively=True,
                        ))
                    made += 1
    return made


async def run(factorio_dir: Path) -> None:
    data_dir = factorio_dir / "data"
    if not (data_dir / "base" / "info.json").exists():
        raise SystemExit(f"{data_dir}/base/info.json not found — pass --factorio-dir")
    version = mod_version(data_dir, "base")
    print(f"Factorio {version} at {factorio_dir}")
    await _purge()

    all_tiers: dict[str, list[dict]] = {}
    all_names: dict[str, str] = {}
    all_modules: dict[str, dict] = {}
    for pack in PACKS:
        print(f"{pack.name}:")
        data = load_pack_data(data_dir, pack)
        names = load_names(data_dir, pack.mods)
        owner = Owners(data_dir, pack.mods)

        # which mod defines each crafting category: the first machine that can craft it
        category_owner: dict[str, str] = {}
        for kind in ("assembling-machine", "furnace", "rocket-silo"):
            for e in data.get(kind, []):
                for c in e.get("crafting_categories") or []:
                    category_owner.setdefault(c, e["__mod"])

        recipes = convert_recipes(data["recipe"], owner, pack.slug, lambda c, fb: category_owner.get(c, fb))
        recipes += mining_recipes(data.get("resource", []), data.get("tile", []), "base", owner, pack.slug)
        print(f"  {len(data['recipe'])} recipe prototypes + {len(data.get('resource', []))} resources "
              f"-> {len(recipes)} recipes")
        for r in recipes:
            MACHINE_NAMES[r.type] = r.machine

        mods_meta = {
            mod: {
                "id": mod, "name": MOD_NAMES[mod],
                "version": mod_version(data_dir, mod) + (" (Space Age)" if mod == "base" and pack.slug == "space-age" else ""),
            }
            for mod in pack.mods
        }
        await import_recipes(
            recipes, TagIndex(Path("/nonexistent")), TagIndex(Path("/nonexistent"), kind="fluid"),
            game_name="Factorio", game_slug="factorio", game_version_str=".".join(version.split(".")[:2]),
            packs=[PackSpec(pack.name, pack.slug, version, set(pack.mods))],
            mods_meta=mods_meta, recipe_metric="throughput", source_priority=0,
        )
        for machine, lst in speed_tiers(data, names).items():
            known = {(t["name"], t["mod"]) for t in all_tiers.get(machine, [])}
            all_tiers.setdefault(machine, []).extend(t for t in lst if (t["name"], t["mod"]) not in known)
        all_names.update(names)
        for mod in module_catalog(data, names, owner):
            all_modules.setdefault(mod["item_id"], mod)

    await _apply_machine_data(all_tiers)
    print(f"  Module upgrades stored: {await _apply_modules(list(all_modules.values()), all_tiers)}")
    print(f"  Display names updated: {await _apply_display_names(all_names)}")


